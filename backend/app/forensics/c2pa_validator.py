"""C2PA content-credential validator (TASK 3.3).

C2PA manifests are cryptographically signed "nutrition labels" embedded by cameras, editors and
AI generators (Adobe Firefly, OpenAI/DALL-E, Microsoft, Google, Leica, Nikon, Samsung...). They
answer: was this captured by a camera, edited, or generated by AI - and was it altered after
signing?

Absence of a manifest proves nothing (most media has none, and platforms strip it); the report
says so explicitly to avoid false accusations.
"""

from __future__ import annotations

import contextlib
import json
import logging
import re
from pathlib import Path
from typing import Any

from app.schemas.forensics import C2paReport, C2paVerdict

logger = logging.getLogger(__name__)

IPTC = "http://cv.iptc.org/newscodes/digitalsourcetype/"
AI_GENERATED_TYPES = {"trainedAlgorithmicMedia", "algorithmicMedia"}
AI_EDITED_TYPES = {"compositeWithTrainedAlgorithmicMedia", "compositeSynthetic"}
CAPTURE_TYPES = {"digitalCapture", "computationalCapture", "negativeFilm", "positiveFilm", "print"}
EDIT_ACTIONS = {
    "c2pa.edited", "c2pa.color_adjustments", "c2pa.cropped", "c2pa.filtered", "c2pa.resized",
    "c2pa.drawing", "c2pa.placed", "c2pa.removed", "c2pa.transcoded", "c2pa.converted",
}  # fmt: skip
AI_TOOL_PATTERN = re.compile(
    r"dall[\s·-]?e|chatgpt|openai|midjourney|firefly|stable\s?diffusion|imagen|gemini|"
    r"bing image creator|designer|sora|runway|leonardo|ideogram|flux|grok",
    re.IGNORECASE,
)
#: Validation codes that do not mean the content was tampered with.
NON_FATAL_CODES = {
    "signingCredential.untrusted",
    "signingCredential.ocsp.skipped",
    "signingCredential.ocsp.inaccessible",
    "timeStamp.untrusted",
    "timeStamp.mismatch",
}
NO_MANIFEST_SUMMARY = (
    "Sem credenciais de conteúdo (C2PA). A maioria das fotos e vídeos não tem, e redes sociais "
    "costumam apagá-las: isso não prova que a mídia é falsa nem verdadeira."
)


class C2paValidator:
    def inspect(self, path: Path, mime_type: str | None = None) -> C2paReport:
        try:
            import c2pa
        except Exception:
            return C2paReport(
                verdict=C2paVerdict.UNAVAILABLE,
                summary="Verificação C2PA indisponível (instale com .\\run.ps1 -Full).",
            )
        try:
            reader = c2pa.Reader(str(path))
        except Exception as exc:
            if "ManifestNotFound" in type(exc).__name__ or "ManifestNotFound" in str(exc):
                return C2paReport(verdict=C2paVerdict.NO_MANIFEST, summary=NO_MANIFEST_SUMMARY)
            logger.info("c2pa could not read %s: %s", path.name, exc)
            return C2paReport(
                verdict=C2paVerdict.NO_MANIFEST,
                summary=NO_MANIFEST_SUMMARY,
                validation_errors=[
                    f"Formato não suportado pela verificação C2PA ({type(exc).__name__})."
                ],
            )
        try:
            store = json.loads(reader.json())
        finally:
            with contextlib.suppress(Exception):
                reader.close()
        return interpret_manifest_store(store)


def _actions(manifest: dict[str, Any]) -> list[dict[str, Any]]:
    found: list[dict[str, Any]] = []
    for assertion in manifest.get("assertions") or []:
        if str(assertion.get("label", "")).startswith("c2pa.actions"):
            found.extend((assertion.get("data") or {}).get("actions") or [])
    return found


def _generator(manifest: dict[str, Any]) -> str | None:
    info = manifest.get("claim_generator_info") or []
    names = [str(i.get("name")) for i in info if isinstance(i, dict) and i.get("name")]
    if names:
        return ", ".join(names)
    generator = manifest.get("claim_generator")
    return str(generator).split("/")[0] if generator else None


def interpret_manifest_store(store: dict[str, Any]) -> C2paReport:
    manifests = store.get("manifests") or {}
    manifest = manifests.get(store.get("active_manifest")) or next(iter(manifests.values()), {})
    if not manifest:
        return C2paReport(verdict=C2paVerdict.NO_MANIFEST, summary=NO_MANIFEST_SUMMARY)

    actions = _actions(manifest)
    source_types = {str(a.get("digitalSourceType", "")).removeprefix(IPTC) for a in actions} - {""}
    action_names = [str(a.get("action")) for a in actions if a.get("action")]
    generator = _generator(manifest)
    signature = manifest.get("signature_info") or {}
    signed_by = signature.get("issuer") or signature.get("common_name")

    statuses = store.get("validation_status") or []
    codes = [str(s.get("code")) for s in statuses if isinstance(s, dict)]
    fatal = [c for c in codes if c not in NON_FATAL_CODES]
    untrusted = "signingCredential.untrusted" in codes

    ai_tool = None
    if (
        source_types & AI_GENERATED_TYPES
        or source_types & AI_EDITED_TYPES
        or (generator and AI_TOOL_PATTERN.search(generator))
    ):
        ai_tool = generator

    if fatal:
        verdict = C2paVerdict.INVALID_SIGNATURE
        summary = (
            "A assinatura de conteúdo não confere: a mídia foi alterada depois de assinada "
            f"({', '.join(fatal[:3])})."
        )
    elif source_types & AI_GENERATED_TYPES or (ai_tool and not source_types):
        # The tool name only decides when the manifest declares no source type at all.
        verdict = C2paVerdict.AI_GENERATED
        summary = f"As credenciais de conteúdo declaram que a mídia foi gerada por IA ({ai_tool})."
    elif source_types & AI_EDITED_TYPES:
        verdict = C2paVerdict.AI_EDITED
        tool = ai_tool or "ferramenta não informada"
        summary = f"As credenciais declaram que a mídia foi editada com IA ({tool})."
    elif source_types & CAPTURE_TYPES:
        edits = [a for a in action_names if a in EDIT_ACTIONS]
        if edits:
            verdict = C2paVerdict.EDITED
            summary = (
                f"Captura original de câmera, depois editada ({', '.join(sorted(set(edits)))})."
            )
        else:
            verdict = C2paVerdict.CAMERA_CAPTURE
            summary = (
                "As credenciais indicam uma captura original de câmera, sem edições registradas."
            )
    else:
        verdict = C2paVerdict.SIGNED_UNKNOWN
        summary = "A mídia tem credenciais de conteúdo, mas não declara como foi criada."

    if verdict is not C2paVerdict.INVALID_SIGNATURE:
        who = f" Assinado por {signed_by}." if signed_by else ""
        trust = (
            " O certificado não está na lista de confiança C2PA: confirme a origem."
            if untrusted
            else ""
        )
        summary += who + trust

    return C2paReport(
        verdict=verdict,
        summary=summary,
        signed_by=signed_by,
        claim_generator=generator,
        ai_tool=ai_tool,
        actions=action_names,
        validation_errors=[c for c in codes if c not in {"signingCredential.untrusted"}],
    )
