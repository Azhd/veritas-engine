"""Builds C2PA-signed test images at test time (no third-party fixture downloads).

A throwaway CA + leaf certificate (ES256) signs a JPEG whose manifest declares how it was made
(e.g. ``trainedAlgorithmicMedia`` = generated by AI). The CA is not trusted by C2PA, so readers
report the signature as untrusted, which the validator must handle too.
"""

from __future__ import annotations

import datetime as dt
import io
import json
from pathlib import Path

C2PA_SOURCE = "http://cv.iptc.org/newscodes/digitalsourcetype/"


def _certificates() -> tuple[bytes, bytes]:
    from cryptography import x509
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

    now = dt.datetime.now(dt.UTC)
    ca_key = ec.generate_private_key(ec.SECP256R1())
    ca_name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "Veritas Test Root CA")])
    ca_cert = (
        x509.CertificateBuilder()
        .subject_name(ca_name)
        .issuer_name(ca_name)
        .public_key(ca_key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - dt.timedelta(days=1))
        .not_valid_after(now + dt.timedelta(days=30))
        .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
        .add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=True,
                crl_sign=True,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .add_extension(x509.SubjectKeyIdentifier.from_public_key(ca_key.public_key()), False)
        .sign(ca_key, hashes.SHA256())
    )
    leaf_key = ec.generate_private_key(ec.SECP256R1())
    leaf_cert = (
        x509.CertificateBuilder()
        .subject_name(
            x509.Name(
                [
                    x509.NameAttribute(NameOID.COMMON_NAME, "Veritas Test Signer"),
                    x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Veritas Test Org"),
                ]
            )
        )
        .issuer_name(ca_name)
        .public_key(leaf_key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - dt.timedelta(days=1))
        .not_valid_after(now + dt.timedelta(days=30))
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=False,
                crl_sign=False,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.EMAIL_PROTECTION]), False)
        .add_extension(
            x509.AuthorityKeyIdentifier.from_issuer_public_key(ca_key.public_key()), False
        )
        .sign(ca_key, hashes.SHA256())
    )
    chain = leaf_cert.public_bytes(serialization.Encoding.PEM) + ca_cert.public_bytes(
        serialization.Encoding.PEM
    )
    key = leaf_key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )
    return chain, key


def signed_jpeg(
    path: Path, *, generator: str, source_type: str, edits: tuple[str, ...] = ()
) -> Path:
    """Write a JPEG at ``path`` carrying a signed C2PA manifest."""
    import c2pa
    from PIL import Image

    raw = io.BytesIO()
    Image.new("RGB", (96, 64), (200, 80, 40)).save(raw, format="JPEG")
    raw.seek(0)
    manifest = {
        "claim_generator_info": [{"name": generator, "version": "1.0"}],
        "title": "test image",
        "format": "image/jpeg",
        "assertions": [
            {
                "label": "c2pa.actions",
                "data": {
                    # C2PA requires the first action to be "created" (or "opened").
                    "actions": [
                        {"action": "c2pa.created", "digitalSourceType": C2PA_SOURCE + source_type},
                        *({"action": edit} for edit in edits),
                    ]
                },
            }
        ],
    }
    chain, key = _certificates()
    info = c2pa.C2paSignerInfo(b"es256", chain, key, None)
    signer = c2pa.Signer.from_info(info)
    builder = c2pa.Builder.from_json(json.dumps(manifest))
    with path.open("wb") as out:
        builder.sign(signer, "image/jpeg", raw, out)
    return path
